#!/usr/bin/env python3
"""Hand-computed self-test for ref_scada.py. Run it after ANY edit to the alarm state machine.

This file exists because defect #25 got all the way into a scored experiment. The reference's own
docstring said an on-delay of 300 ms at a 100 ms scan "fires on the third scan of the condition,
not the fourth", and the code beside it implemented the fourth. Calibration could not see it:
calibration runs ref_scada through verify.py, and verify.py grades against reference answers
generated by ref_scada, so the oracle was being compared with itself and agreed perfectly. Three
models — fable5.1, opus5 and sonnet5 — independently implemented the documented reading and were
all marked wrong.

The expectations below are derived BY HAND from the scenario files and the spec, never by running
ref_scada and copying what it printed. That is the whole point: an expectation copied from the
implementation tests nothing.

The timer rule being pinned: each scan observing the condition true accumulates one whole scan
period, so the N-th consecutive true scan has accumulated N*scan_ms, and the event fires at the
first N with N*scan_ms >= delay_ms. on_delay_ms=0 therefore fires on the very first true scan.

usage: python3 selftest_scada.py        # exits non-zero on any mismatch
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from ref_scada import run  # noqa: E402

# (t_ms, kind, event) triples, hand-derived. Scans land on multiples of scan_ms from 0 to t_end.
EXPECT = {
    # scan=100, on_delay=300. pv crosses 80 at t=200, so the true scans are 200(N=1), 300(N=2),
    # 400(N=3). 3*100 >= 300 first holds at N=3 => ACT at 400. The buggy code wanted t-200 >= 300,
    # i.e. the fourth scan, t=500.
    "s02_on_delay": [(400, "HI", "ACT")],

    # scan=100, on_delay=0, off_delay=300, t_end=1000.
    #   t=100 pv=90: first true scan, 1*100 >= 0 => ACT at 100.
    #   t=400 pv=20: false scans begin; t=500 pv=90 goes true again BEFORE 300 ms elapsed, so the
    #                off-timer resets completely and no CLR is emitted. (This is the spec's
    #                "timer resets completely" clause, exercised on the off side.)
    #   t=800 pv=20: false scans 800(N=1), 900(N=2), 1000(N=3) => 3*100 >= 300 => CLR at 1000.
    # The buggy code wanted t-800 >= 300 => t=1100, which is past t_end, so it emitted NO clear at
    # all and the scenario silently stopped testing the off-delay it was written to test.
    "s06_off_delay": [(100, "HI", "ACT"), (1000, "HI", "CLR")],

    # scan=100, t_end=1200. HI: limit 80, deadband 4, on=200, off=100, priority 2.
    #                        HIHI: limit 100, deadband 2, on=0, off=0, priority 1.
    #   t=200 pv=95: HI true scans 200(N=1), 300(N=2) => 2*100 >= 200 => HI ACT at 300.
    #   t=600 pv=60: HI is active, so it clears only below limit-deadband = 76. 60 < 76, so the
    #                latched condition drops. False scan 600(N=1): 1*100 >= 100 => HI CLR at 600.
    #   t=900 pv=110: HIHI true, on_delay=0 => HIHI ACT at 900 (priority 1).
    #                 HI also true again: scans 900(N=1), 1000(N=2) => HI ACT at 1000.
    "s11_combined": [(300, "HI", "ACT"), (600, "HI", "CLR"),
                     (900, "HIHI", "ACT"), (1000, "HI", "ACT")],

    # The planted trap: the condition breaks one scan before the on-delay expires, so nothing may
    # ever be emitted. It must stay empty under the corrected timing too — a one-scan shift in the
    # timer is exactly the kind of change that would quietly disarm this trap.
    "s03_delay_aborted": [],
}


def main():
    bad = 0
    for name, want in EXPECT.items():
        scen = json.loads((HERE / "scenarios" / f"{name}.json").read_text())
        got = [(e["t_ms"], e["kind"], e["event"]) for e in run(scen)["alarm_journal"]]
        if got == want:
            print(f"  ok    {name:<20} {got}")
        else:
            bad += 1
            print(f"  FAIL  {name:<20}\n        expected {want}\n        got      {got}")

    # The journal must also come out in the order the spec mandates, for every scenario, not only
    # the four above: t_ms, then priority ascending, then tag, then kind.
    for f in sorted((HERE / "scenarios").glob("*.json")):
        j = run(json.loads(f.read_text()))["alarm_journal"]
        want = sorted(j, key=lambda e: (e["t_ms"], e["priority"], e["tag"], e["kind"]))
        if j != want:
            bad += 1
            print(f"  FAIL  {f.stem}: journal is not sorted per the specification")

    print(f"\n{len(EXPECT)} hand-computed expectations + an ordering check on every scenario: "
          + ("all passed" if not bad else f"{bad} mismatched"))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
